// Rebuilds the landing page's isometric figure: `node apps/web/figures/build.mjs`.
// Writes the script and styles to apps/web/public/figures/ and the static
// markup to src/components/marketing/figureMarkup.ts, which the landing page
// renders before it loads the script. The output is committed.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const frag = mkdtempSync(join(tmpdir(), "duckops-fig-"));
process.env.FIG_OUT = join(HERE, "..", "public", "figures");
process.env.FIG_FRAG = frag;
await import("./duckops-line.mjs");
const html = readFileSync(join(frag, "duckops-line.html"), "utf8").trim();
rmSync(frag, { recursive: true, force: true });
writeFileSync(
  join(HERE, "..", "src", "components", "marketing", "figureMarkup.ts"),
  `// Generated by figures/build.mjs. Do not edit by hand.\nexport const DUCKOPS_LINE_FIGURE = ${JSON.stringify(html)};\n`,
);
console.log("wrote src/components/marketing/figureMarkup.ts");
